"""Builds ``GATE0-RENDERED-PLANS.md``: the 20 plans a human reads at Gate 0.

Not a test module. ``test_planner_artifact.py`` asserts the committed file
matches what this produces, so the artifact cannot drift from the code; to
regenerate it after an intended change::

    python -m tests.render_gate0

All 20 are rendered, **including the three blocked fixtures**. A blocked fixture
has no ``expect`` block -- it is waiting on a human ruling -- but it does have a
``given``, so its plan renders fine, and that plan is precisely what the ruling
is about. Leaving them out would hide the three questions behind an artifact
that looked complete.
"""

from __future__ import annotations

import re
from pathlib import Path

from evalloop.plan.planner import plan
from evalloop.registry.format import load
from evalloop.registry.loader import RECORDS_DIR, load_records
from evalloop.vocab import parse_situation, parse_tool
from tests.planner_fixture import load_fixture
from tests.test_planner_fixtures import BLOCKED_PATHS, LIVE_PATHS

ARTIFACT = Path(__file__).resolve().parent.parent / "GATE0-RENDERED-PLANS.md"

_FIXTURE_NUMBER = re.compile(r"^(\d\d)_")
_HEADER = """# Gate 0 — the 20 rendered plans

**Generated by `python -m tests.render_gate0`.** `tests/test_planner_artifact.py`
asserts this file matches what the planner renders now, so it cannot drift.

`PLAN.md` §5 makes the human review of these 20 plans **the gate**: "Human reads
all 20 rendered plans and agrees with every one. Fix anything disputed before
M1." Four states appear on every plan, always, even when empty — "nothing is
pending" is information (`USER_EXPERIENCE.md` §3.1).

Seventeen plans come from a fixture that asserts them. **Three come from a
fixture that is blocked on a ruling** and carries no `expect` block; their
plans are rendered anyway, because the plan is what the ruling is about. Each is
marked and says what the question is.

---
"""


def _plan_lines(path: Path, known_ids: frozenset[str], records: tuple) -> list[str]:  # type: ignore[type-arg]
    """One section: the heading, the given, and the rendered plan."""
    number = match.group(1) if (match := _FIXTURE_NUMBER.match(path.name)) else "??"
    blocked = path in set(BLOCKED_PATHS)
    if blocked:
        document = load(path.read_text(encoding="utf-8"))
        given = document["given"]
        assert isinstance(given, dict)
        name = str(document["name"])
        situations = [parse_situation(str(value)) for value in given["situations"]]  # type: ignore[union-attr]
        tools = [parse_tool(str(value)) for value in given["available_tools"]]  # type: ignore[union-attr]
        evidence = dict(given["evidence"])  # type: ignore[arg-type]
    else:
        fixture = load_fixture(path, known_ids)
        name = fixture.name
        situations = list(fixture.situations)
        tools = list(fixture.available_tools)
        evidence = dict(fixture.evidence)

    result = plan(records, situations, tools, evidence)
    lines = [
        f"## {number} — {name}" + ("  ⚠ **BLOCKED ON A RULING**" if blocked else ""),
        "",
    ]
    if blocked:
        lines += [
            f"> This fixture asserts nothing: it is waiting on a human ruling, and the"
            f" plan below is what that ruling is about. See `{path.name}` for the"
            f" options and `S19-REPORT.md`.",
            "",
        ]
    lines += [
        "```",
        f"situations      {', '.join(situation.value for situation in situations)}",
        f"available_tools {', '.join(tool.value for tool in tools) or '(none)'}",
        f"evidence        {evidence or '{}'}",
        "",
        result.render(),
        "```",
        "",
    ]
    return lines


def build_artifact() -> str:
    """The whole file, as a string. Pure apart from reading the fixtures."""
    records = load_records(RECORDS_DIR)
    known_ids = frozenset(record.id for record in records)
    paths = sorted((*LIVE_PATHS, *BLOCKED_PATHS), key=lambda path: path.name)
    lines = [_HEADER]
    for path in paths:
        lines.extend(_plan_lines(path, known_ids, records))
    return "\n".join(lines).rstrip() + "\n"


def main() -> None:
    text = build_artifact()
    ARTIFACT.write_text(text, encoding="utf-8")
    print(text)
    print(f"\n--- wrote {ARTIFACT.relative_to(ARTIFACT.parent)} ---")


if __name__ == "__main__":
    main()
